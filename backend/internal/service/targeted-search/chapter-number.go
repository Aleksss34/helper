package targeted_search

import "regexp"

// reChapterNumber ловит номер главы, идущий следом за словом-маркером
// главы ("глава", "гл."). \b после "гл" — чтобы не зацепить случайные
// слова, начинающиеся на "гл" (например "глубина").
var reChapterNumber = regexp.MustCompile(`(?i)(?:глава|гл\.?)\s*(\d+)\b`)

// ExtractChapterNumber возвращает номер главы в единообразном строковом
// виде ("1", "15", "3"...), одинаковом что при извлечении из
// SectionTitle чанка на этапе индексации, что при извлечении из вопроса
// пользователя на этапе поиска — это критично, потому что сравнение в
// Qdrant идёт как точное совпадение строк.
//
// Пустая строка означает "номер главы не найден" — вызывающий код
// должен в этом случае просто пропустить фильтр по главе и перейти
// к обычной логике (поиск статьи/гибридный поиск).
func ExtractChapterNumber(text string) string {
	if m := reChapterNumber.FindStringSubmatch(text); m != nil {
		return m[1]
	}
	return ""
}
