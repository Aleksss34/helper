// payload article_title".
//
// ВАЖНО: правая часть должна ТОЧНО совпадать с тем, что реально лежит в
// article_title ваших чанков — если после интеграции точный фильтр
// начнёт давать 0 результатов там, где явно должен находить, первым
// делом проверьте эти строки против реальных значений a.Title,
// с которыми вызывается chunkLegislationArticle (именно оно становится
