package service

import "regexp"

// reDecimalNumber ловит номер вида "9.5", "13.11", "15.1" — десятичные
// подпункты (КоАП, ОУГ, ПДД). Проверяется ПЕРВЫМ, потому что такой номер
// уже полностью однозначен сам по себе, независимо от того, стоит ли
// перед ним слово "Статья"/"Пункт" или нет (в ОУГ его вообще нет — см.
// chunkClauseBlock).
var reDecimalNumber = regexp.MustCompile(`\d+\.\d+`)

// reWordNumber ловит номер, идущий следом за словом-маркером статьи —
// используется, когда номер ЦЕЛЫЙ (без десятичной части), поэтому
// reDecimalNumber выше его не поймал. \b перед "п" — чтобы не зацепить
// букву "п" внутри случайного слова (например "депутат").
var reWordNumber = regexp.MustCompile(`(?i)(?:статья|ст\.?|пункт|\bп\.?)\s*(\d+)\b`)

// ExtractArticleNumber возвращает номер статьи/пункта в единообразном
// строковом виде ("4", "9.5", "13.11"...), одинаковом что при извлечении
// из SectionTitle чанка на этапе индексации, что при извлечении из
// вопроса пользователя на этапе поиска — это критично, потому что
// сравнение в Qdrant идёт как точное совпадение строк.
//
// Пустая строка означает "номер не найден" — вызывающий код должен в
// этом случае просто пропустить точный фильтр и уйти в обычный гибридный
// поиск.
func ExtractArticleNumber(text string) string {
	if m := reDecimalNumber.FindString(text); m != "" {
		return m
	}
	if m := reWordNumber.FindStringSubmatch(text); m != nil {
		return m[1]
	}
	return ""
}
